"""usage: python3 mkheader.py ../fontpatch.h  FP comic.patch.json UniversOTS-SJ_wIcon.ltt  IP icons.patch.json Sony_DI_Icons.ttf
           [PC image_cmn_43.uxc.patch.json image_cmn_43.uxc ...]
(the camera's own /usr/share/app files). For each file, the ranges that change: where, how long, a hash of the
original bytes, and the new bytes without the zeros that pad them out to the range's length. A picture file's
patch also lists the picture ids it changes (sorted), for taking loaded copies out of the UI's label store."""
import json, sys

def arr(name, typ, vals, per=16):
    out = ['static const %s %s[] = {' % (typ, name)]
    for i in range(0, len(vals), per):
        out.append('    ' + ','.join(str(v) for v in vals[i:i + per]) + ',')
    out.append('};')
    return '\n'.join(out)

def fnv(b):
    h = 0x811c9dc5
    for c in b: h = ((h ^ c) * 0x01000193) & 0xffffffff
    return h

out = ['/* Generated by mkheader.py. Comic Relief (SIL Open Font License 1.1, Copyright 2013 The Comic Relief',
       '   Project Authors) outlines, reshaped into the slots of the camera\'s own fonts (ILCE-7M2 firmware 4.01).',
       '   The original bytes are only identified by a hash (they stay on the camera). */']
args = sys.argv[2:]
for k in range(0, len(args), 3):
    pre, pj, orig_path = args[k], args[k + 1], args[k + 2]
    js = json.load(open(pj)); p = sorted(js['patches'])
    orig = open(orig_path, 'rb').read()
    olds = [bytes.fromhex(o) for _, o, _ in p]; news = [bytes.fromhex(n) for _, _, n in p]
    for (off, _, _), o, n in zip(p, olds, news):
        assert orig[off:off + len(o)] == o and len(n) == len(o)
    data = [n.rstrip(b'\0') for n in news]          # the rest of each range is zeros
    lo = pre.lower()
    out += ['/* %s: %d ranges, %d bytes */' % (orig_path.split('/')[-1], len(p), sum(len(d) for d in data)),
            '#define %s_SIZE %du' % (pre, len(orig)), '#define %s_COUNT %d' % (pre, len(p)),
            arr(lo + '_head', 'u8', list(orig[:16])),
            arr(lo + '_off', 'u32', [o for o, _, _ in p], 12),
            arr(lo + '_len', 'u16', [len(o) for o in olds], 20),
            arr(lo + '_dlen', 'u16', [len(d) for d in data], 20),
            arr(lo + '_oldhash', 'u32', [fnv(o) for o in olds], 8),     # FNV-1a of the original bytes
            arr(lo + '_new', 'u8', list(b''.join(data)), 32)]
    if 'ids' in js:
        ids = sorted({0x1a000000 | (int(x, 16) & 0xffffff) for x in js['ids']})   # the record ids (0x1a......)
        out += ['#define %s_NRID %d' % (pre, len(ids)), arr(lo + '_rid', 'u32', ids, 8)]
    print(pre, len(p), 'ranges', sum(len(d) for d in data), 'bytes')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
