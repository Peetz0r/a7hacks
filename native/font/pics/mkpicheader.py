maxraw = 0; maxcount = 0; maxruns = 0; args = sys.argv[2:]
allpics = []                                 # (file number, index, picture, its record in the file), for the order
for k in range(0, len(args), 2):
    pre, pj = args[k], args[k + 1]; lo = pre.lower()
