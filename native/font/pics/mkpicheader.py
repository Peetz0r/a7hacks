# the order to do them in (order.txt): the first ones, the rest as they are in the files, the last ones
def matches(rule, x, r):
    w = rule.split()
    if w[0] == 'id': return x[8] == int(w[1], 16)
    if w[0] == 'size': return '%dx%d' % (r['w'], r['h']) == w[1]
    if w[0] == 'stretch': return r['flags'] >> 24 == 0xe8
    if w[0] == 'level': return bool(x[5] >> 29 & 1)
    raise SystemExit('order.txt: what is ' + rule)
rules = [l.split('#')[0].strip() for l in open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'order.txt'))]
rules = [l.split(None, 1) for l in rules if l]
def rank(t):
    for n, (where, rule) in enumerate(rules):
        if matches(rule, t[2], t[3]): return (0, n) if where == 'first' else (2, n)
    return (1, 0)
