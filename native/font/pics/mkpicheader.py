"""usage: python3 mkpicheader.py ../../picpatch.h  PC image_cmn_43.uxc.pics.json  PE image_EVF.uxc.pics.json
          PD image_DSLR_Only_43.uxc.pics.json  PS image_DSC_Only_43.uxc.pics.json
The pictures the font patcher (a7hacks --font-patcher) changes, per file: where each one's data area is and how long, a hash of the original data,
the new data's length and hash, its size unpacked, and our pixels (runs: u16 skip, u16 count, the pixels;
ending with 0, 0; packed with the same LZ77 as the pictures, and shared between pictures that are the same).
No pixels of Sony's are in here: only the ones we drew. Needs uxclz (cc -O2 -DUXCLZ_MAIN -x c ../../uxclz.c)."""
import json, sys, subprocess, os
UXCLZ = os.environ.get('UXCLZ', os.path.join(os.path.dirname(os.path.abspath(__file__)), 'uxclz'))
def pack(b): return subprocess.run([UXCLZ, 'e'], input=b, capture_output=True, check=True).stdout
def arr(name, typ, vals, per=16):
    out = ['static const %s %s[] = {' % (typ, name)]
    for i in range(0, len(vals), per): out.append('    ' + ','.join(str(v) for v in vals[i:i + per]) + ',')
    if not vals: out.append('    0,')
    out.append('};'); return '\n'.join(out)
out = ['/* Generated by font/pics/mkpicheader.py: the camera\'s pictures with lettering in them, with the lettering',
       '   drawn again in Comic Relief (SIL Open Font License 1.1, Copyright 2013 The Comic Relief Project Authors).',
       '   Only the pixels we drew are here; the rest of each picture comes from the camera\'s own file. */']
maxraw = 0; maxcount = 0; maxruns = 0; args = sys.argv[2:]
for k in range(0, len(args), 2):
    pre, pj = args[k], args[k + 1]; lo = pre.lower()
    js = json.load(open(pj)); P = sorted(js['pics'])
    runs = b''; run = []; rlen = []; seen = {}
    for x in P:
        r = bytes.fromhex(x[6]); maxruns = max(maxruns, len(r)); rlen.append(len(r))
        if r not in seen: seen[r] = len(runs); runs += pack(r)
        run.append(seen[r])
    ids = sorted({x[7] for x in P})
    maxraw = max([maxraw] + [x[5] & 0x7fffffff for x in P]); maxcount = max(maxcount, len(P))
    out += ['/* %s: %d pictures, %d bytes of our pixels */' % (pj, len(P), len(runs)),
            '#define %s_SIZE %du' % (pre, js['size']), '#define %s_COUNT %d' % (pre, len(P)),
            arr(lo + '_head', 'u8', list(bytes.fromhex(js['head']))),
            arr(lo + '_off', 'u32', [x[0] for x in P], 12), arr(lo + '_len', 'u32', [x[1] for x in P], 12),
            arr(lo + '_old', 'u32', [x[2] for x in P], 8), arr(lo + '_nlen', 'u32', [x[3] for x in P], 12),
            arr(lo + '_new', 'u32', [x[4] for x in P], 8), arr(lo + '_raw', 'u32', [x[5] for x in P], 12),
            arr(lo + '_run', 'u32', run, 12), arr(lo + '_rlen', 'u32', rlen, 12), arr(lo + '_runs', 'u8', list(runs), 32),
            '#define %s_NRID %d' % (pre, len(ids)), arr(lo + '_rid', 'u32', ids, 8)]
    print(pre, len(P), 'pictures', len(runs), 'bytes')
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hue                                   # the accent colour table (HUE degrees; the same one mkpics used)
out += ['/* the accent colour: Sony\'s orange turned %d degrees; RGB444 -> RGB444, for pictures marked in _raw */' % hue.HUE,
        arr('pic_hue', 'u16', [int(v) for v in hue.LUT], 16)]
# the text accent: entries of color_cmn.uxc (the UI reads it as it needs a colour), only where the file is the
# one we know (its size and hash, with our entries back as they were)
import uxc
col = open(os.path.join(uxc.APP, 'color_cmn.uxc'), 'rb').read()
ce = hue.colours(col)
def fnv32(b):
    h = 0x811c9dc5
    for c in b: h = ((h ^ c) * 0x01000193) & 0xffffffff
    return h
out += ['/* the text accent colours: color_cmn.uxc entries, RGBA bytes as u32 (little endian) */',
        '#define COL_SIZE %du' % len(col), '#define COL_HASH 0x%08xu' % fnv32(col), '#define COL_N %d' % len(ce),
        arr('col_off', 'u32', [o for o, a, b in ce] or [0], 8),
        arr('col_old', 'u32', [int.from_bytes(a, 'little') for o, a, b in ce] or [0], 8),
        arr('col_new', 'u32', [int.from_bytes(b, 'little') for o, a, b in ce] or [0], 8)]
out += ['#define PIC_MAXRAW %du' % maxraw, '#define PIC_MAXCOUNT %d' % max(1, maxcount), '#define PIC_MAXRUNS %du' % maxruns]
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
